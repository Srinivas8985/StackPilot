/**
 * Register dedicated EC2 infrastructure with Nagios
 */
async function registerHost(infraId, userId) {
  const infra = await Infrastructure.findById(infraId).populate('deployment');
  if (!infra) {
    throw new Error(`Infrastructure record ${infraId} not found.`);
  }

  // Authorization check
  if (infra.user.toString() !== userId.toString()) {
    throw new Error(`Unauthorized: User ${userId} does not own infrastructure ${infraId}`);
  }

  // Lifecycle state checks
  if (infra.status !== 'PROVISIONED') {
    throw new Error(`Cannot register monitoring for infrastructure in status ${infra.status}. Terraform provisioning must be PROVISIONED first.`);
  }

  if (infra.configurationStatus !== 'configured') {
    throw new Error(`Cannot register monitoring while host configuration is ${infra.configurationStatus}. Ansible setup must complete first.`);
  }

  // Target IP validation
  validatePublicIp(infra.publicIp);

  // Concurrency lock
  if (activeRegistrations.has(infraId.toString())) {
    throw new Error(`Monitoring registration is already in progress for infrastructure ${infraId}.`);
  }

  activeRegistrations.add(infraId.toString());

  return runWithLock(async () => {
    try {
      ensureHostsDir();
      const hostName = getNagiosHostName(infra._id);
      const hostConfigFile = path.join(NAGIOS_HOSTS_DIR, `${hostName}.cfg`);

      // Generate and write host configuration
      const configContent = generateHostConfig(infra, infra.deployment);
      fs.writeFileSync(hostConfigFile, configContent, 'utf8');

      // Validate configuration syntax
      await validateNagiosConfig();

      // Trigger reload if service daemon is running
      await reloadNagios();

      // Generate baseline services
      const baselineServices = generateBaselineServices(infra, false);

      // Update Infrastructure document
      infra.monitoringStatus = 'registered';
      infra.nagiosHostName = hostName;
      infra.monitoringRegisteredAt = new Date();
      infra.lastMonitoringCheck = new Date();
      infra.monitoringError = null;
      infra.monitoringServices = baselineServices;

      if (typeof infra.save === 'function') {
        await infra.save();
      }

      if (typeof infra.pushLog === 'function') {
        await infra.pushLog(`Nagios monitoring registered successfully for host ${hostName}`, 'success');
      }

      return {
        success: true,
        hostName,
        status: 'registered',
        registeredAt: infra.monitoringRegisteredAt,
        configFile: hostConfigFile,
        servicesCount: baselineServices.length
      };

    } catch (err) {
      console.error(`[NagiosService] Registration failed for ${infraId}:`, err);
      if (infra) {
        infra.monitoringStatus = 'unavailable';
        infra.monitoringError = err.message;
        if (typeof infra.save === 'function') {
          await infra.save();
        }
      }
      throw err;
    } finally {
      activeRegistrations.delete(infraId.toString());
    }
  });
}

/**
 * Deregister dedicated EC2 infrastructure from Nagios and remove configuration
 */
async function deregisterHost(infraId, userId = null) {
  const infra = await Infrastructure.findById(infraId);
  if (!infra) {
    throw new Error(`Infrastructure record ${infraId} not found.`);
  }

  // Authorization check if userId is provided
  if (userId && infra.user.toString() !== userId.toString()) {
    throw new Error(`Unauthorized: User ${userId} does not own infrastructure ${infraId}`);
  }

  return runWithLock(async () => {
    try {
      const hostName = infra.nagiosHostName || getNagiosHostName(infraId);
      const hostConfigFile = path.join(NAGIOS_HOSTS_DIR, `${hostName}.cfg`);

      // Remove configuration file if present
      if (fs.existsSync(hostConfigFile)) {
        fs.unlinkSync(hostConfigFile);
      }

      // Validate remaining Nagios configuration
      await validateNagiosConfig();

      // Reload Nagios daemon
      await reloadNagios();

      // Reset monitoring state in database
      infra.monitoringStatus = 'pending';
      infra.nagiosHostName = null;
      infra.monitoringRegisteredAt = null;
      infra.lastMonitoringCheck = null;
      infra.monitoringError = null;
      infra.monitoringServices = [];

      if (typeof infra.save === 'function') {
        await infra.save();
      }

      if (typeof infra.pushLog === 'function') {
        await infra.pushLog(`Nagios monitoring deregistered for host ${hostName}`, 'info');
      }

      return {
        success: true,
        hostName,
        status: 'pending',
        message: 'Host deregistered from Nagios monitoring successfully.'
      };

    } catch (err) {
      console.error(`[NagiosService] Deregistration error for ${infraId}:`, err);
      if (infra) {
        infra.monitoringError = `Deregistration error: ${err.message}`;
        if (typeof infra.save === 'function') {
          await infra.save();
        }
      }
      throw err;
    }
  });
}

/**
 * Retrieve monitoring status and live check results for an infrastructure host
 */
async function getMonitoringStatus(infraId, userId) {
  const infra = await Infrastructure.findById(infraId).populate('deployment');
  if (!infra) {
    throw new Error(`Infrastructure record ${infraId} not found.`);
  }

  if (infra.user.toString() !== userId.toString()) {
    throw new Error(`Unauthorized: User ${userId} does not own infrastructure ${infraId}`);
  }

  const hostName = infra.nagiosHostName || getNagiosHostName(infraId);
  const hostConfigFile = path.join(NAGIOS_HOSTS_DIR, `${hostName}.cfg`);
  const isRegistered = fs.existsSync(hostConfigFile) || infra.monitoringStatus === 'registered';

  if (!isRegistered) {
    return {
      hostName,
      status: infra.monitoringStatus || 'pending',
      registered: false,
      lastCheck: infra.lastMonitoringCheck,
      error: infra.monitoringError,
      services: []
    };
  }

  // Try parsing real status.dat
  const liveData = parseNagiosStatusFile(hostName);

  if (liveData && liveData.services.length > 0) {
    // Determine overall health based on service states
    const hasCritical = liveData.services.some(s => s.status === 'CRITICAL');
    const hasWarning = liveData.services.some(s => s.status === 'WARNING');
    const overallStatus = hasCritical ? 'critical' : hasWarning ? 'warning' : 'healthy';

    infra.monitoringStatus = overallStatus;
    infra.monitoringServices = liveData.services;
    infra.lastMonitoringCheck = new Date();
    if (typeof infra.save === 'function') {
      await infra.save();
    }

    return {
      hostName,
      status: overallStatus,
      registered: true,
      hostState: liveData.hostStatus?.state || 'UP',
      hostOutput: liveData.hostStatus?.output || 'Host is operational',
      lastCheck: infra.lastMonitoringCheck,
      registeredAt: infra.monitoringRegisteredAt,
      services: liveData.services,
      isLive: true
    };
  }

  // If no live status.dat or daemon is pending initial check cycle
  const currentServices = (infra.monitoringServices && infra.monitoringServices.length > 0)
    ? infra.monitoringServices
    : generateBaselineServices(infra, false);

  return {
    hostName,
    status: infra.monitoringStatus === 'pending' ? 'registered' : (infra.monitoringStatus || 'registered'),
    registered: true,
    hostState: 'UP',
    hostOutput: 'Host registered in Nagios; polling active',
    lastCheck: infra.lastMonitoringCheck || new Date(),
    registeredAt: infra.monitoringRegisteredAt,
    services: currentServices,
    isLive: false,
    note: 'Monitoring registered; awaiting next scheduled Nagios check cycle.'
  };
}

/**
 * Retrieve service checks array specifically
 */
async function getMonitoringServices(infraId, userId) {
  const result = await getMonitoringStatus(infraId, userId);
  return {
    hostName: result.hostName,
    status: result.status,
    services: result.services || []
  };
}

